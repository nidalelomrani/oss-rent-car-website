// Initialize language system
function initLanguageSystem() {
  const savedLang = localStorage.getItem('ossrentcar-lang') || 'fr';
  setLanguage(savedLang);
}

// Set language and update all translatable content
function setLanguage(lang) {
  if (!translations[lang]) lang = 'fr';
  
  localStorage.setItem('ossrentcar-lang', lang);
  document.documentElement.lang = lang;
  
  // Update language toggle UI
  const toggle = document.getElementById('langToggle');
  if (toggle) {
    toggle.setAttribute('data-current', lang);
    const options = toggle.querySelectorAll('.lang-option');
    options.forEach(opt => {
      opt.classList.toggle('active', opt.getAttribute('data-lang') === lang);
    });
  }

  // Update all elements with data-tr attributes
  document.querySelectorAll('[data-tr]').forEach(el => {
    const key = el.getAttribute('data-tr');
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Update HTML tag language attribute for SEO
  document.documentElement.lang = lang;
}

// Setup language toggle button
function setupLanguageToggle() {
  const toggle = document.getElementById('langToggle');
  if (!toggle) return;

  toggle.addEventListener('click', () => {
    const currentLang = toggle.getAttribute('data-current');
    const newLang = currentLang === 'fr' ? 'en' : 'fr';
    setLanguage(newLang);
  });

  // Also allow clicking individual language options
  document.querySelectorAll('.lang-option').forEach(option => {
    option.addEventListener('click', (e) => {
      e.stopPropagation();
      const lang = option.getAttribute('data-lang');
      setLanguage(lang);
    });
  });
}

// Initialize on page load
document.addEventListener('DOMContentLoaded', () => {
  initLanguageSystem();
  setupLanguageToggle();
});
